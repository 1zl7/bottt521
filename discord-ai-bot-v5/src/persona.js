const pickFresh = (arr, recent) => {
  const pool = arr.filter((x) => !recent.includes(x));
  const src = pool.length ? pool : arr;
  const v = src[Math.floor(Math.random() * src.length)];
  recent.push(v);
  if (recent.length > 18) recent.shift();
  return v;
};

class Persona {
  constructor() { this.recent = []; }

  // نص الناس → رد جاهز (او null لو ما يستاهل رد وهو مو موجه لك)
  reply(text, { direct = false } = {}) {
    const t = normAr(text);
    for (const r of RULES) if (r.re.test(t)) return pickFresh(r.lines, this.recent);
    if (direct) return pickFresh(GENERIC, this.recent);
    return null;
  }

  opener() { return pickFresh(OPENERS, this.recent); }
}

